def _render_overview() -> None:
    st.markdown(
        """
### Что делает приложение

Pipeline переводит русскоязычный текст в **метаграф** — иерархическое
представление, где базовые узлы соответствуют сущностям, рёбра — отношениям,
а метавершины и метарёбра агрегируют фрагменты графа в объекты более высокого
уровня абстракции.

Преобразование разделено на две фазы:

- **Phase 1** — тяжёлая, детерминированная, кэшируется по хэшу текста и
  настроек морфо-синтаксиса/клауз/анафоры. Включает разбор, выделение клауз,
  построение графа и опциональные шаги анафоры и NP-свёртки.
- **Phase 2** — лёгкая, перезапускается мгновенно при смене пресета или
  тоглов агрегации. Строит уровни L1 и L2 метаграфа поверх готового
  семантического графа из Phase 1.

Архитектура подчинена принципу объяснимости: каждый элемент графа и
метаграфа несёт `provenance` — указатель на правило, входы и стадию,
породившие этот элемент. Никаких скрытых смысловых выводов LLM — только
правила, морфо-синтаксис и явные эвристики.
        """
    )

    st.markdown("### Схема pipeline")
    st.markdown(_PIPELINE_HTML, unsafe_allow_html=True)

    st.markdown("### Иерархия уровней метаграфа")
    st.markdown(_HIERARCHY_HTML, unsafe_allow_html=True)
    st.markdown(
        """
- **L0 — семантический граф.** Узлы соответствуют именным концептам и
  предикатам, рёбра — UD-ролям (`nsubj`, `obj`, `obl` и т. д.). Это
  базовый слой, на котором стоит вся агрегация.
- **L1 — клаузы как метавершины.** Каждая клауза становится метавершиной
  с типом `clause:{clause_type}`. Между клаузами строятся метарёбра
  `shared_entity` по общим леммам.
- **L2 — тематические агрегаты.** Метавершины уровня 2 объединяют
  L1-клаузы по разным критериям: параграф, кластер по общим сущностям
  (union-find), центрированность на лемме (`entity_centric`), класс
  предиката; между ними строятся метарёбра `topic_overlap` по
  пересечениям.

Эта иерархия строится «снизу вверх» и поддерживает холархию: одна
L1-клауза может одновременно входить в несколько L2-метавершин (например,
и в параграф, и в кластер по сущности). Это согласуется с многомерной
метаграфовой моделью данных и знаний.
        """
    )


